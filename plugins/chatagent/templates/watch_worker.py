#!/usr/bin/env python3
"""chatagent watcher

Generated by `chatagent watch`. Polls one HTTP JSON API (REST or GraphQL),
finds the items that are new or changed since the last pass, and posts each one
to a chatagent agent's inbox as an event. Standard library only.

Config (daemonctl set <slug> --set key=value):
  agent           chatagent agent name (its inbox receives the events)
  source          short label, e.g. "linear"
  url             endpoint to poll
  method          GET or POST (default GET; GraphQL is POST)
  body            request body as JSON text (GraphQL: {"query": "..."})
  headers         JSON object; values may reference secrets as ${NAME}
  items_path      dotted path to the list of items, e.g. data.issues.nodes
  id_field        dotted path inside an item to its id (default id)
  version_field   dotted path that changes when the item changes, e.g. updatedAt
  title_template  Python format string over the item, e.g. "{identifier} {title}"
  url_field       dotted path to a link for the item (optional)
  first_run       "skip" (default: remember what exists, report only later changes) or "emit"
"""

import json
import os
import re
import sys
import urllib.request

sys.path.insert(0, os.path.join(
    os.path.expanduser(os.environ.get("DAEMON_AGENT_HOME", "~/.daemon-agent")), "lib"))

from daemon_runtime import run_once  # noqa: E402


def dig(obj, path):
    for part in [p for p in (path or "").split(".") if p]:
        if isinstance(obj, list):
            obj = obj[int(part)] if part.isdigit() and int(part) < len(obj) else None
        elif isinstance(obj, dict):
            obj = obj.get(part)
        else:
            return None
    return obj


class Flat(dict):
    """Lets title_template say {state.name} style keys via {state_name}."""
    def __missing__(self, key):
        return ""


def flatten(item, prefix=""):
    out = Flat()
    if isinstance(item, dict):
        for k, v in item.items():
            key = prefix + k
            if isinstance(v, dict):
                out.update(flatten(v, key + "_"))
            else:
                out[key] = v
    return out


def inbox_settings(agent):
    home = os.path.expanduser(os.environ.get("CHATAGENT_HOME", "~/.chatagent"))
    adir = os.path.join(home, "agents", agent)
    with open(os.path.join(adir, "agent.json")) as f:
        cfg = json.load(f)
    port = cfg.get("channels", {}).get("inbox", {}).get("inbox_port", 8790)
    token = ""
    with open(os.path.join(adir, "secrets.env")) as f:
        for line in f:
            if line.startswith("INBOX_TOKEN="):
                token = line.split("=", 1)[1].strip()
    return port, token


def main(ctx):
    c = ctx.config
    headers = {"content-type": "application/json", "user-agent": "chatagent-watcher"}
    for k, v in json.loads(c.get("headers") or "{}").items():
        headers[k] = re.sub(r"\$\{([A-Z0-9_]+)\}", lambda m: ctx.secret(m.group(1)), str(v))
    method = (c.get("method") or "GET").upper()
    body = c.get("body")
    data = ctx.fetch(c["url"], method=method, headers=headers,
                     json_body=json.loads(body) if body else None)
    items = dig(data, c.get("items_path", ""))
    if not isinstance(items, list):
        raise RuntimeError("items_path %r did not point at a list" % c.get("items_path"))

    first = "_versions" not in ctx.state
    versions = ctx.state.get("_versions", {})
    changed = []
    for item in items:
        iid = str(dig(item, c.get("id_field", "id")))
        ver = str(dig(item, c.get("version_field", "")) or "")
        if versions.get(iid) != ver:
            changed.append((iid, item, iid in versions))
        versions[iid] = ver
    # Keep the memory bounded to what the source still returns plus a margin.
    if len(versions) > 5000:
        keep = {str(dig(i, c.get("id_field", "id"))) for i in items}
        versions = {k: v for k, v in versions.items() if k in keep}
    ctx.state["_versions"] = versions

    if first and c.get("first_run", "skip") == "skip":
        ctx.log.info("baseline recorded", items=len(items))
        return {"baseline": len(items)}

    port, token = inbox_settings(c["agent"])
    posted = 0
    for iid, item, existed in changed:
        flat = flatten(item)
        title = (c.get("title_template") or "{id}").format_map(flat)
        payload = {
            "source": c.get("source", "watch"),
            "id": "%s:%s" % (iid, dig(item, c.get("version_field", "")) or ""),
            "title": ("Changed: " if existed else "New: ") + title,
            "text": json.dumps(item, ensure_ascii=False)[:3000],
            "url": dig(item, c.get("url_field", "")) or "",
        }
        ctx.fetch("http://127.0.0.1:%s/event" % port, method="POST",
                  headers={"x-chatagent-token": token}, json_body=payload)
        posted += 1
    return {"items": len(items), "posted": posted}


run_once(main)
