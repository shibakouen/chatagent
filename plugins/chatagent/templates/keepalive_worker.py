#!/usr/bin/env python3
"""chatagent keepalive

Generated by `chatagent always-on`. Runs as a daemon-agent service and keeps one
chatagent agent alive: if its tmux session is gone it starts it again, and it
reports the channel heartbeats so `daemonctl health` shows a stalled connector.
"""

import json
import os
import subprocess
import sys
import time

sys.path.insert(0, os.path.join(
    os.path.expanduser(os.environ.get("DAEMON_AGENT_HOME", "~/.daemon-agent")), "lib"))

from daemon_runtime import serve  # noqa: E402

TMUX_CANDIDATES = ["/opt/homebrew/bin/tmux", "/usr/local/bin/tmux", "/usr/bin/tmux"]


def tmux_bin():
    for p in TMUX_CANDIDATES:
        if os.path.exists(p):
            return p
    return "tmux"


def running(name):
    return subprocess.run([tmux_bin(), "has-session", "-t", "ca-" + name],
                          capture_output=True).returncode == 0


def heartbeats(name):
    home = os.path.expanduser(os.environ.get("CHATAGENT_HOME", "~/.chatagent"))
    state = os.path.join(home, "agents", name, "state")
    out = {}
    if not os.path.isdir(state):
        return out
    for kind in os.listdir(state):
        p = os.path.join(state, kind, "heartbeat.json")
        try:
            with open(p) as f:
                hb = json.load(f)
            out[kind] = {"connected": hb.get("connected"), "age_s": round(time.time() - os.path.getmtime(p))}
        except (OSError, ValueError):
            pass
    return out


def main(ctx):
    name = ctx.config["agent"]
    if not running(name):
        restarts = ctx.state.get("restarts", 0)
        ctx.log.warn("agent not running, starting", agent=name, restarts=restarts)
        r = subprocess.run([ctx.config["node"], ctx.config["cli"], "start", name],
                           capture_output=True, text=True, timeout=180)
        ctx.state["restarts"] = restarts + 1
        if r.returncode != 0:
            raise RuntimeError("start failed: " + (r.stdout + r.stderr)[-800:])
        ctx.log.info("agent started", agent=name)
    hb = heartbeats(name)
    stale = [k for k, v in hb.items() if v["age_s"] > 180 or v["connected"] is False]
    if stale:
        ctx.log.warn("channel not healthy", agent=name, channels=",".join(stale))
    return {"agent": name, "channels": len(hb), "stale": len(stale)}


serve(main, interval=30)
